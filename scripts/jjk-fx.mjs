const sequencerOn = () => !!(game.modules.get("sequencer")?.active && typeof globalThis.Sequence === "function");
const jb2aOn = () => !!(game.modules.get("JB2A_DnD5e")?.active || game.modules.get("jb2a_patreon")?.active);
/** "auto": our sigil on every cast + our impacts when JB2A is missing; "own": only ours; "off": none of ours. */
export function visualMode() { return setting("techniqueFX", "auto"); }
export const ownImpacts = () => visualMode() === "own" || (visualMode() === "auto" && !jb2aOn());

function reducedMotion() {
  try { return globalThis.matchMedia?.("(prefers-reduced-motion: reduce)")?.matches === true; } catch { return false; }
}

const gmIds = () => [...(game.users ?? [])].filter((u) => u.isGM).map((u) => u.id);
const isHidden = (token) => !!(token?.document?.hidden ?? token?.hidden);
/** The scene level a token stands on (Foundry 14), so its effects stay on that floor. */
export function levelOf(token) {
  const doc = token?.document ?? token;
  return typeof doc?.level === "string" ? doc.level : doc?.level?.id ?? null;
}

/** Who may see an effect at this token: everyone, only the GMs (hidden token), or nobody. Pure, tested. */
export function audienceFor(token) {
  if (!token) return null;
  return isHidden(token) ? gmIds() : "all";
}

function play(shape, at, { color = null, scale = 1.5, below = false, size = null } = {}) {
  if (!sequencerOn() || !at || visualMode() === "off" || !setting("animations", true)) return false;
  const audience = audienceFor(at);
  if (!audience || (Array.isArray(audience) && !audience.length)) return false;
  try {
    const seq = new globalThis.Sequence();
    const eff = seq.effect().file(effectFile(shape)).atLocation(at);
    // A hidden token must not be revealed by its own technique: only the GMs see the effect.
    if (Array.isArray(audience)) eff.forUsers(audience);
    if (size) eff.size(size, { gridUnits: true }); else eff.scaleToObject(scale);
    if (color) eff.tint(color);
    if (below) eff.belowTokens();
    const level = levelOf(at);
    if (level) eff.onLevels?.(level);
    eff.fadeIn(80).fadeOut(240);
    if (reducedMotion()) eff.playbackRate?.(0.75);
    seq.play();
    return true;
  } catch (err) { console.warn(`${ID} | effect`, err); return false; }
}

/* ------------------------------------------------------------------ chat cards → cast / hit */
function cardItem(message) {
  const uuid = message?.flags?.dnd5e?.item?.uuid;
  if (!uuid) return null;
  try { return globalThis.fromUuidSync?.(uuid) ?? null; } catch { return null; }
}
function cardTargets(message) {
  return [...(message?.flags?.dnd5e?.targets ?? [])].map((t) => {
    try { const doc = globalThis.fromUuidSync?.(t.uuid); return { ac: Number(t.ac), token: doc?.object ?? doc?.getActiveTokens?.()?.[0] ?? null }; }
    catch { return { ac: Number(t.ac), token: null }; }
  });
}
function speakerToken(message, item) {
  const id = message?.speaker?.token;
  return (id && globalThis.canvas?.tokens?.get?.(id)) || item?.actor?.getActiveTokens?.()?.[0] || null;
}

/** What a JJK chat card means for the sound and the picture (pure, tested). */
export function readCard(message) {
  const d5 = message?.flags?.dnd5e ?? {};
  const kind = d5.messageType === "usage" ? "cast" : d5.messageType === "roll" && d5.roll?.type === "attack" ? "attack"
    : d5.messageType === "roll" && d5.roll?.type === "damage" ? "damage" : null;
  if (!kind) return null;
  const item = cardItem(message);
  if (!item?.flags?.[ID] || item.flags[ID].cePool) return null;
  return { kind, item, fx: fxFor(item) };
}

const midiOn = () => !!game.modules.get("midi-qol")?.active;
const aaHandles = (item) => { try { return !!api().aaHandles?.(item); } catch { return false; } };
const aaHasSound = (item) => !!item?.flags?.autoanimations?.audio?.a01?.enable;
function cardActivity(message) {
  const uuid = message?.flags?.dnd5e?.activity?.uuid;
  if (!uuid) return null;
  try { return globalThis.fromUuidSync?.(uuid) ?? null; } catch { return null; }
}
/** The domain opening has its own event sound; its usage card stays quiet (pure, tested). */
export function isDomainUse(item, message) {
  const f = item?.flags?.[ID] ?? {};
  const actId = message?.flags?.dnd5e?.activity?.id ?? String(message?.flags?.dnd5e?.activity?.uuid ?? "").split(".").pop();
  if (f.domainActivity) return !actId || f.domainActivity === actId;
  return /^domain expansion/i.test(String(item?.name ?? ""));
}

export function onChatMessage(message) {
  if (message?.visible === false) return;           // a blind or private roll stays silent for whoever cannot see it
  const card = readCard(message);
  if (!card) return;
  const { kind, item } = card;
  const activity = cardActivity(message);
  const fx = fxFor(item, activity);
  const mine = message.isAuthor ?? message.author?.id === game.user?.id;
  const aa = aaHandles(item);
  if (kind === "cast") {
    if (fx.cast && !isDomainUse(item, message) && !(aa && aaHasSound(item))) playSound(fx.cast, { volume: fx.castVolume });
    if (!mine || !fx.sigil || aa) return;
    const source = speakerToken(message, item);
    play("sigil", source, { color: fx.color, scale: fx.technique ? 1.9 : 1.5, below: true });
    if (ownImpacts() && fx.technique) {
      const targets = cardTargets(message).map((t) => t.token).filter(Boolean);
      setTimeout(() => { for (const tk of targets) play(fx.shape, tk, { color: fx.color, scale: 1.6 }); }, 380);
    }
    return;
  }
  if (kind === "attack" && !midiOn()) {
    const total = Number(message.rolls?.[0]?.total);
    const crit = !!message.rolls?.[0]?.isCritical;
    const targets = cardTargets(message);
    const hits = targets.filter((t) => crit || !Number.isFinite(t.ac) || !Number.isFinite(total) || total >= t.ac);
    if ((hits.length || !targets.length) && !(aa && aaHasSound(item))) setTimeout(() => playSound(fx.impact, { volume: 0.9 }), 250);
    if (mine && ownImpacts() && !aa) for (const t of hits) if (t.token) play(fx.shape, t.token, { color: fx.color ?? null, scale: 1.4 });
  }
}

/* ------------------------------------------------------------------ Midi-QOL: hits travel on the socket */
const SOCKET = `module.${ID}`;
/** Accepts only the module's own sound files from the socket (pure, tested). */
export function safeSocketSound(msg) {
  if (msg?.type !== "jjk-sfx" || typeof msg.src !== "string") return null;
  if (!msg.src.startsWith(`${ROOT}/sounds/`) || msg.src.includes("..") || !/\.ogg$/.test(msg.src)) return null;
  return { src: msg.src, volume: Math.max(0, Math.min(1, Number(msg.volume) || 1)) };
}
function broadcastSound(src, volume = 1) {
  playSound(src, { volume });
  try { game.socket?.emit?.(SOCKET, { type: "jjk-sfx", src, volume }); } catch { /* */ }
}
function onMidiAttack(workflow) {
  const item = workflow?.item;
  if (!item?.flags?.[ID] || item.flags[ID].cePool) return;
  const fx = fxFor(item, workflow.activity ?? null);
  const hits = [...(workflow.hitTargets ?? [])];
  const aa = aaHandles(item);
  if ((hits.length || !(workflow.targets?.size)) && !(aa && aaHasSound(item))) setTimeout(() => broadcastSound(fx.impact, 0.9), 250);
  if (ownImpacts() && !aa) for (const tk of hits) play(fx.shape, tk?.object ?? tk, { color: fx.color ?? null, scale: 1.4 });
}

/* ------------------------------------------------------------------ screen shake (Foundry 14 core) */
/** How hard each moment shakes the camera (pure, tested). Pixels at 100% zoom, milliseconds. */
export function shakeProfile(kind) {
  return ({ blackFlash: { duration: 450, maxDisplacement: 14 }, domain: { duration: 900, maxDisplacement: 9 },
    clash: { duration: 700, maxDisplacement: 12 } })[kind] ?? null;
}
/** Shake the viewer's canvas with the core CanvasShakeEffect, only on the scene where it happened. */
export function shakeScreen(kind, actor = null, sceneId = null) {
  const profile = shakeProfile(kind);
  const Shake = globalThis.foundry?.canvas?.animation?.CanvasShakeEffect;
  const stage = globalThis.canvas?.stage;
  if (!profile || !Shake || !stage || !setting("screenShake", true) || reducedMotion()) return false;
  const viewed = globalThis.canvas?.scene?.id;
  const here = sceneId ? sceneId === viewed : !actor || (actor.getActiveTokens?.() ?? []).some((tk) => (tk.document ?? tk)?.parent?.id === viewed);
  if (!here) return false;
  try { Promise.resolve(new Shake({ target: stage, smoothness: 0.6, returnSpeed: 0.15, ...profile }).play()).catch(() => null); return true; }
  catch (err) { console.warn(`${ID} | shake`, err); return false; }
}

/* ------------------------------------------------------------------ module events from documents */
export function onActorUpdate(actor, changes) {
  const flags = changes?.flags?.[ID];
  if (!flags) return;
  // The flag holds { activityUuid } (or true on older worlds): either means a Black Flash just landed.
  const bf = flags.pendingBlackFlash;
  if (bf === true || (bf && typeof bf === "object")) { playSound(eventSound("black-flash")); shakeScreen("blackFlash", actor); }
  if ("domainState" in flags || "-=domainState" in flags) {
    const before = domainMemory.get(actor.uuid) ?? null;
    const now = actor.getFlag?.(ID, "domainState") ?? null;
    domainMemory.set(actor.uuid, now ? { open: !!now.open, openingId: now.openingId, clash: !!(now.clash && !now.clash.resolved) } : null);
    if (now?.open && now.openingId && now.openingId !== before?.openingId) { playSound(eventSound("domain-open"), { volume: 1 }); shakeScreen("domain", actor, now.sceneId); }
    else if (before?.open && !now?.open) { playSound(eventSound("domain-close")); lastClose.set(actor.uuid, Date.now()); }
    if (now?.open && now.clash && !now.clash.resolved && !before?.clash) { playSound(eventSound("domain-clash")); shakeScreen("clash", actor, now.sceneId); }
  }
}
const domainMemory = new Map();
const lastClose = new Map();

export function onEffectCreated(effect) {
  const kind = effect?.flags?.[ID]?.kind;
  if (kind === "zone" || effect?.flags?.[ID]?.zone) playSound(eventSound("zone"));
  else if (kind === "burnout" || effect?.flags?.[ID]?.burnout) {
    // Closing a domain creates the burnout at once: let the closing sound breathe first.
    const closed = lastClose.get(effect.parent?.uuid);
    const delay = closed && Date.now() - closed < 2000 ? 900 : 0;
    if (delay) setTimeout(() => playSound(eventSound("burnout")), delay); else playSound(eventSound("burnout"));
  }
  else if (kind === "maxOutputActive") playSound(eventSound("max-output"));
}

/* ------------------------------------------------------------------ domain backdrops (GM writes, everyone sees) */
const isActiveGM = () => !!game.user?.isGM && (game.users?.activeGM ? game.users.activeGM.id === game.user.id : true);

/**
 * The shape a domain zone covers, as {type, …} in scene pixels: the Region's first shape, or the circle of a
 * MeasuredTemplate (the fallback when a Region could not be created; its radius already fits the map).
 */
export function zoneShape(zone) {
  if (zone?.documentName === "MeasuredTemplate" || zone?.t) {
    const grid = zone.parent?.grid ?? {};
    const r = (Number(zone.distance) || 0) * (Number(grid.size) || 100) / (Number(grid.distance) || 5);
    return r > 0 && Number.isFinite(zone.x) && Number.isFinite(zone.y) ? { type: "circle", x: zone.x, y: zone.y, radius: r } : null;
  }
  return zone?.shapes?.[0] ?? null;
}

/** Drawing data that fills a domain zone's shape with the backdrop texture (pure, tested). */
export function backdropDrawing(zone, texture) {
  const shape = zoneShape(zone);
  if (!shape) return null;
  let x, y, w, h, s;
  if (shape.type === "polygon") {
    const xs = shape.points.filter((_, i) => i % 2 === 0), ys = shape.points.filter((_, i) => i % 2 === 1);
    x = Math.min(...xs); y = Math.min(...ys); w = Math.max(...xs) - x; h = Math.max(...ys) - y;
    s = { type: "p", width: w, height: h, points: shape.points.map((v, i) => v - (i % 2 === 0 ? x : y)) };
  } else {
    const rx = shape.radiusX ?? shape.radius, ry = shape.radiusY ?? shape.radius;
    if (![shape.x, shape.y, rx, ry].every(Number.isFinite)) return null;
    x = shape.x - rx; y = shape.y - ry; w = rx * 2; h = ry * 2;
    s = { type: "e", width: w, height: h };
  }
  const data = {
    x, y, shape: s, texture, fillType: globalThis.CONST?.DRAWING_FILL_TYPES?.PATTERN ?? 2, fillColor: "#ffffff", fillAlpha: 0.86,
    strokeWidth: 6, strokeColor: "#0d0a0e", strokeAlpha: 0.85, locked: true, hidden: false,
    elevation: Number.isFinite(zone.elevation?.bottom) ? zone.elevation.bottom : Number.isFinite(zone.elevation) ? zone.elevation : 0, sort: -1000,
    flags: { [ID]: { domainBackdrop: zone.id, zoneKind: zone.documentName ?? "Region", domain: zone.flags?.[ID]?.domain, openingId: zone.flags?.[ID]?.openingId } }
  };
  // Foundry 14 levels: the backdrop lives on the same levels as the barrier it fills.
  const levels = zone.levels ? [...zone.levels] : [];
  if (levels.length) data.levels = levels;
  return data;
}

function backdropFor(zone) {
  const actorUuid = zone?.flags?.[ID]?.domain;
  let actor = null;
  try { actor = actorUuid ? globalThis.fromUuidSync?.(actorUuid) : null; } catch { /* */ }
  const chosen = actor?.getFlag?.(ID, "domainBackdrop");
  if (chosen === "none") return null;
  if (chosen && FX_TABLE.backdrops.includes(chosen)) return chosen;
  const tech = actor?.getFlag?.(ID, "technique") ?? actor?.items?.find?.((i) => i.flags?.[ID]?.technique)?.flags?.[ID]?.technique;
  const domainItem = actor?.items?.find?.((i) => i.flags?.[ID]?.domainActivity);
  const resolved = FX_TABLE.techniques[tech] ? tech : domainItem ? techniqueOf(domainItem) : null;
  return FX_TABLE.techniques[resolved]?.backdrop ?? "void";
}

const ownBackdrops = (scene, zoneId) => [...(scene?.drawings ?? [])].filter((d) => d.flags?.[ID]?.domainBackdrop && (!zoneId || d.flags[ID].domainBackdrop === zoneId));

async function writeBackdrop(scene, data, existing) {
  const create = async (d) => {
    if (existing.length) {
      await scene.updateEmbeddedDocuments("Drawing", [{ _id: existing[0].id, ...d }]);
      if (existing.length > 1) await scene.deleteEmbeddedDocuments("Drawing", existing.slice(1).map((x) => x.id));
    } else await scene.createEmbeddedDocuments("Drawing", [d]);
  };
  try { await create(data); }
  catch (err) {
    // A core without Drawing levels refuses the field: keep the backdrop, drop the field, say so once.
    if (!data.levels) throw err;
    console.warn(`${ID} | domain backdrop: levels not accepted, drawn on every level`, err);
    const { levels: _levels, ...rest } = data;
    await create(rest);
  }
}

async function syncBackdrop(zone, deleted = false) {
  if (!isActiveGM() || !zone?.flags?.[ID]?.domain || zone.flags[ID].clashZone) return;
  const scene = zone.parent;
  const existing = ownBackdrops(scene, zone.id);
  const name = !deleted && setting("domainBackdrops", true) ? backdropFor(zone) : null;
  const data = name ? backdropDrawing(zone, backdropFile(name)) : null;
  try {
    if (!data) { if (existing.length) await scene.deleteEmbeddedDocuments("Drawing", existing.map((d) => d.id)); return; }
    await writeBackdrop(scene, data, existing);
  } catch (err) { console.warn(`${ID} | domain backdrop`, err); }
}

/** Drawings left behind by a lost close (their zone is gone): removed at ready and by the domain cleanup. */
export async function sweepBackdrops(scenes = game.scenes ?? []) {
  if (!isActiveGM()) return 0;
  let n = 0;
  for (const scene of scenes) {
    const orphans = ownBackdrops(scene).filter((d) => !scene.regions?.get?.(d.flags[ID].domainBackdrop) && !scene.templates?.get?.(d.flags[ID].domainBackdrop));
    if (!orphans.length) continue;
    try { await scene.deleteEmbeddedDocuments("Drawing", orphans.map((d) => d.id)); n += orphans.length; } catch { /* */ }
  }
  return n;
}

