Hooks.once("init", () => {
  const K = (key) => ({ name: `JJK5E.Settings.${key}.Name`, hint: `JJK5E.Settings.${key}.Hint` });
  const reg = (key, data) => game.settings.register(ID, key, { config: true, ...K(key), ...data });
  reg("sfxEnabled", { scope: "client", type: Boolean, default: true });
  reg("sfxVolume", { scope: "client", type: Number, default: 0.7, range: { min: 0, max: 1, step: 0.05 } });
  reg("techniqueFX", { scope: "client", type: String, default: "auto",
    choices: { auto: "JJK5E.Settings.techniqueFX.auto", own: "JJK5E.Settings.techniqueFX.own", off: "JJK5E.Settings.techniqueFX.off" } });
  reg("domainBackdrops", { scope: "world", type: Boolean, default: true });
  reg("screenShake", { scope: "client", type: Boolean, default: true });
});

Hooks.once("ready", () => {
  if (game.system?.id !== "dnd5e") return;
  const mod = game.modules.get(ID)?.api;
  if (mod) mod.fx = { fxFor, playSound, shakeScreen, eventSound, chooseBackdrop, sweepBackdrops, ownImpacts, visualMode, techniqueOf, table: FX_TABLE };
  for (const actor of game.actors ?? []) {
    const s = actor.getFlag?.(ID, "domainState");
    if (s) domainMemory.set(actor.uuid, { open: !!s.open, openingId: s.openingId, clash: !!(s.clash && !s.clash.resolved) });
  }
  Hooks.on("createChatMessage", (message) => { try { onChatMessage(message); } catch (err) { console.warn(`${ID} | fx`, err); } });
  Hooks.on("updateActor", (actor, changes) => { try { onActorUpdate(actor, changes); } catch (err) { console.warn(`${ID} | fx`, err); } });
  Hooks.on("createActiveEffect", (effect) => { try { onEffectCreated(effect); } catch (err) { console.warn(`${ID} | fx`, err); } });
  Hooks.on("createRegion", (region) => syncBackdrop(region));
  Hooks.on("updateRegion", (region, changes) => { if ("shapes" in (changes ?? {})) syncBackdrop(region); });
  Hooks.on("deleteRegion", (region) => syncBackdrop(region, true));
  Hooks.on("createMeasuredTemplate", (tpl) => syncBackdrop(tpl));
  Hooks.on("updateMeasuredTemplate", (tpl, changes) => { if (["x", "y", "distance"].some((k) => k in (changes ?? {}))) syncBackdrop(tpl); });
  Hooks.on("deleteMeasuredTemplate", (tpl) => syncBackdrop(tpl, true));
  // Midi-QOL folds the attack roll into the usage card: hits come from its workflow and travel on the socket.
  if (midiOn()) Hooks.on("midi-qol.AttackRollComplete", (workflow) => { try { onMidiAttack(workflow); } catch (err) { console.warn(`${ID} | fx`, err); } });
  game.socket?.on?.(SOCKET, (msg) => { const ok = safeSocketSound(msg); if (ok) playSound(ok.src, { volume: ok.volume }); });
  Hooks.on("updateActor", (actor, changes) => {
    if (!isActiveGM() || !foundry.utils.hasProperty(changes ?? {}, `flags.${ID}`) || !("domainBackdrop" in (changes.flags[ID] ?? {}) || "-=domainBackdrop" in (changes.flags[ID] ?? {}))) return;
    for (const scene of game.scenes ?? []) for (const zone of [...(scene.regions ?? []), ...(scene.templates ?? [])]) if (zone.flags?.[ID]?.domain === actor.uuid) syncBackdrop(zone);
  });
  if (isActiveGM()) setTimeout(() => sweepBackdrops().catch(() => null), 2500);
});
