/**
 * JJK5e technique audio-visuals: one cast sound per technique, an impact sound per family, module events
 * (domain, clash, Black Flash, The Zone, burnout), ink effects tinted per technique, and domain backdrops.
 *
 * Almost everything listens to documents that every client receives (chat cards, actor flags, active effects,
 * regions), so each player hears the sound once, at their own volume. Midi-QOL folds attack rolls into one card, so
 * its hit sounds travel on the module socket instead. Visuals are played by the author only, because Sequencer
 * already shares them with the table; hidden tokens are never drawn for players.
 * All media under sounds/, effects/ and textures/ is generated by tools/build-fx.py (no third-party assets).
 */
